const assert = require('node:assert/strict');
const { loadSource } = require('./lib/load-source.cjs');
const { ImageNavigation } = loadSource('media/modules/image-navigation.ts');
const { installImageLoad } = loadSource('media/modules/image-load.ts');
const { parseAutomationRequest, parsePythonCommand } = loadSource('shared/viewer-protocol.ts');
const { MeasurementResults } = loadSource('media/modules/measure/results.ts');
const { imageMeasurement, imageHistogram } = loadSource('media/modules/active-image.ts');

async function main() {
  let cancellations = 0, resets = 0, signal;
  const nav = new ImageNavigation({ cancelWorkers: () => cancellations++, resetFile: () => resets++, setSignal: next => signal = next });
  const cache = key => ({ cacheKey: key, snapshot: { restore() { restored.push(key); } } });
  const restored = [];
  const initial = nav.signal;
  const first = nav.openFile(null);
  assert.ok(initial.aborted);
  const firstSignal = signal;
  nav.openFile(cache('a'));
  assert.ok(firstSignal.aborted);
  nav.openFile(cache('b'));
  assert.equal(nav.restore('a').cacheKey, 'a');
  assert.deepEqual(restored, ['a']);
  const cancelledBeforePlane = cancellations;
  const resetBeforePlane = resets;
  nav.changePlane();
  assert.equal(cancellations, cancelledBeforePlane, 'plane steps retain worker source caches');
  assert.equal(resets, resetBeforePlane, 'plane steps retain GPU resources and raw state');
  assert.equal(nav.restore('b'), null, 'plane changes cannot restore a file-switch cache');
  nav.changeLevel();
  assert.equal(cancellations, cancelledBeforePlane + 1);
  assert.equal(resets, resetBeforePlane, 'TIFF level transitions retain file state');
  assert.notEqual(nav.generation, first);
  const waiting = nav.waitUntilReady(nav.generation);
  nav.changePlane();
  assert.equal(await waiting, false, 'superseding navigation releases queued image actions');
  const readyGeneration = nav.generation;
  const ready = nav.waitUntilReady(readyGeneration);
  nav.markReady(readyGeneration - 1);
  nav.markReady(readyGeneration);
  assert.equal(await ready, true, 'layer additions wait for the new source to finish');
  nav.clear();
  assert.ok(nav.signal.aborted);
  assert.equal(await nav.waitUntilReady(nav.generation), false, 'cleared images cannot strand queued actions');
  nav.openFile(null);
  const failedLoad = nav.waitUntilReady(nav.generation);
  nav.markFailed(nav.generation);
  assert.equal(await failedLoad, false);
  assert.equal(nav.restore('a'), null);

  let generation = 1, installs = 0, completions = 0, contexts = 0, release;
  const result = { canvas: { getContext() { contexts++; return {}; } }, imageData: {} };
  const host = { isCurrent: value => value === generation, install() { installs++; }, complete() { completions++; }, draw: async () => {} };
  assert.equal(await installImageLoad(host, {}, result, 0), false);
  assert.equal(installs, 0, 'stale decodes never install');
  await installImageLoad(host, { _pendingRenderData: {} }, result, 1);
  assert.equal(contexts, 0, 'deferred GPU placeholder must not acquire a 2D context');
  host.draw = () => new Promise(resolve => { release = resolve; });
  const drawing = installImageLoad(host, {}, result, 1);
  generation++; release();
  assert.equal(await drawing, false);
  assert.equal(completions, 1, 'an async draw superseded by navigation must not finalize');

  const request = (operation, args) => ({ type: 'automationRequest', id: 'request-1', operation, args });
  assert.equal(parseAutomationRequest(request('pixel', { x: 0, y: 1 })).args.y, 1);
  for (const input of [request('unknown', {}), request('pixel', {x:-1,y:0}), request('region', {x:0,y:0,width:0,height:1}), request('display', {settings:{gamma:{in:NaN,out:1}}}), request('capture', {zoom:Infinity})]) assert.throws(() => parseAutomationRequest(input));
  assert.throws(() => parsePythonCommand({id:'x',operation:'display',arguments:{gamma:[1]}}));
  assert.throws(() => parsePythonCommand({id:'x',operation:'display',arguments:{value_range:[5,1]}}));
  assert.throws(() => parsePythonCommand({id:'x',operation:'select',arguments:{index:-1}}));
  assert.equal(parsePythonCommand({id:'x',operation:'display',arguments:{exposure:2,gamma:[2.2,2.2]}}).arguments.exposure, 2);

  const data = new Float32Array([-3, 4]);
  const image = { raster: {data,width:2,height:1,channels:1,isFloat:false,typeMax:32767,sourceNumericType:'int16'}, typeMin:-32768, page:2, pageCount:4, stats:{min:-3,max:4} };
  const measured = imageMeasurement(image, 'a');
  const histogram = imageHistogram(image);
  assert.equal(measured.data, data); assert.equal(histogram.rawData, data);
  assert.equal(measured.typeMin, histogram.typeMin); assert.equal(measured.typeMax, histogram.typeMax);
  assert.equal(measured.page, 2); assert.equal(histogram.stats.min, -3);
  assert.equal(imageHistogram({...image,planar:[data]}).planarData[0], data);

  let source = measured, pixelWidth = 1, frames = [], changed = 0;
  global.requestAnimationFrame = fn => { frames.push(fn); return frames.length; };
  const results = new MeasurementResults({getSource:()=>source,getCalibration:()=>({pixelWidth,pixelHeight:1,unit:'px',origin:'none'}),getRois:()=>[{id:'roi',kind:'rect',name:'region',x:0,y:0,width:2,height:1}],provenance:()=>({pixelWidth,fileName:source.fileName}),extraColumns:()=>({batch:source.fileName}),changed:()=>changed++});
  results.collecting = true;
  results.schedule(); results.schedule();
  assert.equal(frames.length,1,'ROI drags coalesce until the next frame'); frames.shift()();
  source = {...measured,fileName:'b'}; pixelWidth=2; results.measure();
  assert.equal(results.collected.get('a').provenance.pixelWidth,1,'collected rows retain their own calibration');
  assert.equal(results.collected.get('b').provenance.pixelWidth,2);
  assert.equal(results.exportRows().length,2); assert.equal(changed,1);
  console.log('Viewer boundaries: navigation, deferred loading, protocol validation and measurement ownership passed.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
