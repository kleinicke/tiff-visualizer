#!/usr/bin/env node
// Generates docs/commands.md from package.json.
//
// The command reference is the one page guaranteed to rot if written by hand:
// commands get renamed, keybindings move, and nobody remembers the doc. Running
// this in `pretest` means a stale reference fails CI instead of shipping.
//
// Usage: node scripts/generate-command-docs.js [--check]
//
// ---------------------------------------------------------------------------
// Conventions for docs/ (kept here rather than in CLAUDE.md, which stays short)
// ---------------------------------------------------------------------------
//
// - docs/ ships inside the VSIX and is opened by the tiffVisualizer.showDocumentation
//   command in VS Code's built-in markdown preview. There is deliberately no
//   walkthrough contribution: nothing opens on install.
// - docs/commands.md is generated. New commands need their ID added to a GROUPS
//   entry below, otherwise they land in "Other".
// - Links between doc pages must be relative (./formats.md). Relative links work
//   in the markdown preview, on GitHub, and in a future static site. README is the
//   exception — Marketplace rendering needs absolute URLs there.
// - Doc images must be .png or .gif. .vscodeignore strips *.jpg and *.tif globally,
//   so a JPEG silently vanishes from the package with no error.
// - Do not exclude docs/ from the VSIX. Verify with: npx vsce ls | grep docs/
// - showDocumentation allowlists docs/*.md. Its optional `page` argument exists so
//   panels can deep-link (showDocumentation('measure.md')).

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkg = require(path.join(root, 'package.json'));
const outPath = path.join(root, 'docs', 'commands.md');

const contributes = pkg.contributes || {};
const commands = contributes.commands || [];
const keybindings = contributes.keybindings || [];
const config = (contributes.configuration || {}).properties || {};
const editors = contributes.customEditors || [];

/** Keybindings indexed by command, formatted for a human. */
const keysByCommand = new Map();
for (const binding of keybindings) {
	const combos = [];
	if (binding.key) { combos.push(binding.key); }
	if (binding.mac && binding.mac !== binding.key) { combos.push(`${binding.mac} (macOS)`); }
	const pretty = combos
		.map(c => c.split('+').map(part => `\`${part}\``).join(' + '))
		.join(' / ');
	keysByCommand.set(binding.command, pretty);
}

// Grouping is editorial: the flat package.json order is registration order,
// which is not how anyone looks a command up.
const GROUPS = [
	{
		title: 'Opening and navigation',
		doc: './getting-started.md',
		ids: ['tiffVisualizer.openDicomFolder', 'tiffVisualizer.zoomIn', 'tiffVisualizer.zoomOut',
			'tiffVisualizer.resetZoom', 'tiffVisualizer.pastePosition'],
	},
	{
		title: 'Display settings',
		doc: './rendering.md',
		ids: ['tiffVisualizer.setNormalizationRange', 'tiffVisualizer.setGamma', 'tiffVisualizer.setBrightness',
			'tiffVisualizer.toggleNanColor', 'tiffVisualizer.toggleRgb24Mode', 'tiffVisualizer.applyColormap',
			'tiffVisualizer.convertColormapToFloat', 'tiffVisualizer.revertToOriginal',
			'tiffVisualizer.resetAllSettings'],
	},
	{
		title: 'Inspection panels',
		doc: './viewing.md',
		ids: ['tiffVisualizer.toggleHistogram', 'tiffVisualizer.toggleMetadata', 'tiffVisualizer.toggleMeasure',
			'tiffVisualizer.toggleColorPickerMode', 'tiffVisualizer.toggleDebayer'],
	},
	{
		title: 'Collections and comparison',
		doc: './collections.md',
		ids: ['tiffVisualizer.browseAndAddToCollection', 'tiffVisualizer.selectForCompare',
			'tiffVisualizer.compareWithSelected', 'tiffVisualizer.openComparisonPanel'],
	},
	{
		title: 'Layers',
		doc: './layers.md',
		ids: ['tiffVisualizer.toggleLayers', 'tiffVisualizer.addLayer'],
	},
	{
		title: 'Export and interchange',
		doc: './export.md',
		ids: ['tiffVisualizer.exportLayers', 'tiffVisualizer.copyImage', 'tiffVisualizer.copyImageInfo',
			'tiffVisualizer.openAsPointCloud'],
	},
	{
		title: 'Help',
		doc: './index.md',
		ids: ['tiffVisualizer.showDocumentation'],
	},
];

const byId = new Map(commands.map(c => [c.command, c]));
const grouped = new Set(GROUPS.flatMap(g => g.ids));
const ungrouped = commands.filter(c => !grouped.has(c.command));

const lines = [];
lines.push('[← Documentation index](./index.md)');
lines.push('');
lines.push('# Command reference');
lines.push('');
lines.push('<!-- Generated by scripts/generate-command-docs.js from package.json. Do not edit by hand. -->');
lines.push('');
lines.push('Every command is available from the Command Palette under the');
lines.push('**TIFF Visualizer** category. Many are also in the right-click menu inside an');
lines.push('open image.');
lines.push('');

function renderRows(ids) {
	const rows = [];
	for (const id of ids) {
		const cmd = byId.get(id);
		if (!cmd) { continue; }
		const key = keysByCommand.get(id) || '';
		rows.push(`| ${cmd.title} | \`${id}\` | ${key} |`);
	}
	return rows;
}

for (const group of GROUPS) {
	const rows = renderRows(group.ids);
	if (rows.length === 0) { continue; }
	lines.push(`## ${group.title}`);
	lines.push('');
	lines.push('| Command | ID | Keybinding |');
	lines.push('| --- | --- | --- |');
	lines.push(...rows);
	lines.push('');
	lines.push(`See [${group.doc.replace(/^\.\/|\.md$/g, '')}](${group.doc}).`);
	lines.push('');
}

if (ungrouped.length > 0) {
	lines.push('## Other');
	lines.push('');
	lines.push('| Command | ID | Keybinding |');
	lines.push('| --- | --- | --- |');
	lines.push(...renderRows(ungrouped.map(c => c.command)));
	lines.push('');
}

lines.push('## Keybindings');
lines.push('');
lines.push('These are active only while a Scientific Image Visualizer tab has focus, so');
lines.push('they do not shadow your normal editor bindings.');
lines.push('');
lines.push('| Keybinding | Command |');
lines.push('| --- | --- |');
for (const binding of keybindings) {
	const cmd = byId.get(binding.command);
	lines.push(`| ${keysByCommand.get(binding.command)} | ${cmd ? cmd.title : binding.command} |`);
}
lines.push('');
lines.push('Inside the image, `←` / `→` step through a dataset, collection or multi-page');
lines.push('TIFF, and `[` / `]` step through TIFF pages. Inside the measure panel, single');
lines.push('letters select tools — see [measurement](./measure.md).');
lines.push('');

lines.push('## Settings');
lines.push('');
const configKeys = Object.keys(config);
if (configKeys.length > 0) {
	lines.push('| Setting | Default | Description |');
	lines.push('| --- | --- | --- |');
	for (const key of configKeys) {
		const prop = config[key];
		lines.push(`| \`${key}\` | \`${JSON.stringify(prop.default)}\` | ${prop.description || ''} |`);
	}
} else {
	lines.push('This extension contributes no settings.');
}
lines.push('');
lines.push('Display settings — normalization, gamma, brightness — are deliberately *not*');
lines.push('VS Code settings. They live for the lifetime of the window and reset when it');
lines.push('closes. See [rendering](./rendering.md).');
lines.push('');

lines.push('## File associations');
lines.push('');
lines.push('| Editor | Opens |');
lines.push('| --- | --- |');
for (const editor of editors) {
	const patterns = (editor.selector || []).map(s => `\`${s.filenamePattern}\``).join(', ');
	lines.push(`| ${editor.displayName} (\`${editor.viewType}\`) | ${patterns} |`);
}
lines.push('');
lines.push('The `.option` editor is registered for formats VS Code already previews, so');
lines.push('it does not take them over — reach it with **Open With…**. See');
lines.push('[formats](./formats.md).');
lines.push('');

const output = lines.join('\n');

if (process.argv.includes('--check')) {
	const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
	if (existing !== output) {
		console.error('docs/commands.md is out of date. Run: npm run docs:commands');
		process.exit(1);
	}
	console.log('docs/commands.md is up to date.');
} else {
	fs.writeFileSync(outPath, output);
	console.log(`Wrote ${path.relative(root, outPath)} (${commands.length} commands).`);
}
